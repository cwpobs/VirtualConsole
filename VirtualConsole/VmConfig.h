#pragma once

#include <string>

// Настройка виртуальной машины: консоль или видеоконсоль (см.
// VideoConsole.h) - для программ разницы нет, они всегда пишут в
// TextVRAM/TextAttr одинаково (см. main.cpp). Читается из
// необязательного текстового файла рядом с boot.asm - если файла нет
// или в нём нет нужного ключа, используются значения по умолчанию
// (машина стартует с видеоконсолью без какой-либо настройки, как
// просил пользователь).
struct VmConfig
{
    bool useVideoConsole = true;
    int videoConsoleScale = 2;

    // path - путь к конфигу (обычно "config.txt" рядом с boot.asm).
    // Отсутствие файла - не ошибка, возвращает значения по умолчанию.
    // Формат - "ключ=значение" по строке, "#" в начале строки -
    // комментарий. Известные ключи:
    //   console = video | text
    //   video_scale = <целое >= 1>
    static VmConfig load(const std::string& path);
};
